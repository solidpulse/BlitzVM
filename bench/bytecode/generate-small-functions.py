#!/usr/bin/env python3
"""Generate the checked-in 50-call-site workload reproducibly (no runtime code generation)."""
from pathlib import Path

lines = ["<?php", "// Generated by generate-small-functions.py; 50 distinct roots and direct call sites."]
for i in range(50):
    lines += [f"function small_{i}($a, $x) {{", "    $v = $a['value'];",
              "    if ($a['enabled'] === true) {", f"        $v = $v + $x + {i};", "    } else {",
              f"        $v = $v - {i};", "    }", "    return $v + $a['bias'];", "}"]
lines += ["function benchmark() {", "    $a = ['value' => 7, 'enabled' => true, 'bias' => 3];",
          "    $sum = 0;", "    for ($cycle = 0; $cycle < 12000; $cycle = $cycle + 1) {"]
for i in range(50):
    lines += [f"        $sum = $sum + small_{i}($a, $cycle);"]
lines += ["    }", "    return $sum;", "}",
          "for ($round = 0; $round < 10; $round = $round + 1) {", "    $start = hrtime(true);",
          "    $result = benchmark();", "    $elapsed = hrtime(true) - $start;",
          "    echo 'round=', $round, ' ns=', $elapsed, ' result=', $result, \"\\n\";", "}"]
Path(__file__).with_name("02-small-functions.php").write_text("\n".join(lines) + "\n")
