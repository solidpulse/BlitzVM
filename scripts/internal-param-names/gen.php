#!/usr/bin/env php
<?php
/**
 * Writes the parameter lists of the methods of the classes BlitzVM implements in
 * Java to src/main/resources/dev/phpruntime/class-params.tsv, for binding named
 * arguments to those methods.
 *
 * The class names come from the runtime itself: every internal class name of the
 * local php is offered to BlitzVM's class_exists(), and the names it knows are
 * kept. Names the local php does not have are dropped, so a method BlitzVM has and
 * php does not keeps no names. mysqli is special: BlitzVM builds its template on
 * first use, so class_exists() does not see it, but php declares the class.
 *
 * Parameter names, by-reference and variadic flags are php's
 * (ReflectionMethod::getParameters()), because they decide what a named call means.
 *
 * Usage: scripts/internal-param-names/gen.php
 *
 * The file format, one line per method:
 *
 *   Class::method \t name:byref:variadic \t name:byref:variadic ...
 *
 * A method with no parameters is the key alone. Class and method names are php's
 * spelling; lookups in the runtime are case-insensitive.
 */

declare(strict_types=1);

$root = dirname(__DIR__, 2);

function classesKnownToBlitz(string $root): array
{
    $php = [];
    foreach (array_merge(get_declared_classes(), get_declared_interfaces()) as $class) {
        if ((new ReflectionClass($class))->isInternal()) {
            $php[] = $class;
        }
    }
    $php = array_values(array_unique(array_filter($php, 'is_string')));
    $nameFile = tempnam(sys_get_temp_dir(), 'blitz-classes-');
    file_put_contents($nameFile, implode("\n", $php) . "\n");
    $probe = tempnam(sys_get_temp_dir(), 'blitz-probe-');
    file_put_contents($probe, <<<'CODE'
<?php
$names = explode("\n", trim(file_get_contents($argv[1])));
foreach ($names as $name) {
    if ($name === '') {
        continue;
    }
    if (class_exists($name) || interface_exists($name) || trait_exists($name) || enum_exists($name)) {
        echo $name, "\n";
    }
}
CODE);
    $bin = $root . '/bin/php-truffle';
    $output = shell_exec(escapeshellarg($bin) . ' ' . escapeshellarg($probe) . ' ' . escapeshellarg($nameFile));
    unlink($nameFile);
    unlink($probe);
    if ($output === null) {
        fwrite(STDERR, "cannot run $bin\n");
        exit(1);
    }
    $names = preg_split('/\R/', trim($output));
    // Template built on first use, so class_exists() cannot see it; php has it.
    foreach (['mysqli', 'mysqli_result', 'mysqli_stmt'] as $lazy) {
        $names[] = $lazy;
    }
    $names = array_values(array_unique(array_filter($names, static fn (string $n): bool => $n !== '')));
    sort($names, SORT_STRING);
    return $names;
}

$classes = classesKnownToBlitz($root);
$lines = [];
$skipped = 0;
foreach ($classes as $class) {
    if (!class_exists($class) && !interface_exists($class) && !enum_exists($class)) {
        $skipped++;
        continue;
    }
    $reflection = new ReflectionClass($class);
    foreach ($reflection->getMethods() as $method) {
        $fields = [$reflection->getName() . '::' . $method->getName()];
        foreach ($method->getParameters() as $param) {
            $fields[] = $param->getName() . ':' . ($param->isPassedByReference() ? '1' : '0')
                . ':' . ($param->isVariadic() ? '1' : '0');
        }
        $lines[] = implode("\t", $fields);
    }
}

sort($lines, SORT_STRING);

$header = "# Generated by scripts/internal-param-names/gen.php from php " . PHP_VERSION . ".\n"
    . "# Class::method \t name:byref:variadic ...; a method with no parameters\n"
    . "# is the key alone. Class and method lookups are case-insensitive.\n";

$target = $root . '/src/main/resources/dev/phpruntime/class-params.tsv';
if (!is_dir(dirname($target)) && !mkdir(dirname($target), 0777, true) && !is_dir(dirname($target))) {
    fwrite(STDERR, "cannot create " . dirname($target) . "\n");
    exit(1);
}
file_put_contents($target, $header . implode("\n", $lines) . "\n");

printf("%d classes, %d methods, %d classes missing from php\n", count($classes), count($lines), $skipped);
