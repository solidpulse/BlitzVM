#!/usr/bin/env python3
"""Generates the DFA scanners for timelib's date grammar with re2java (re2c 4.x).

The named definitions and the 50 rule expressions of parse_date.re (timelib 2022.17, as
bundled in php-src 8.5.12; MIT License) are compiled into one deterministic scanner per group
of consecutive rules. A single scanner for all rules exceeds the JVM's 64 KB method limit;
taking the longest match across groups, with ties going to the earlier group, is the same as
timelib's longest match with ties to the earlier rule. ParseDate runs the rule actions.

Usage: scripts/date-scanner/gen.py [path/to/re2java]
Writes src/main/java/dev/phpruntime/timelib/DateScanner{0..3}.java. Building re2c 4.6:
download https://github.com/skvadrik/re2c/releases/download/4.6/re2c-4.6.tar.xz,
then ./configure --prefix=$HOME/.local --disable-docs && make && make install.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src", "main", "java", "dev", "phpruntime", "timelib")
RE2JAVA = sys.argv[1] if len(sys.argv) > 1 else "re2java"
# Rule index boundaries: each group must compile into one JVM method (checked by javac).
GROUPS = [0, 32, 42, 44, 50]

src = open(os.path.join(HERE, "parse_date.re"), encoding="latin-1").read().split("\n")
start = src.index("/*!re2c")                      # the definitions block
end = src.index("*/", start)
definitions = "\n".join(src[start + 1:end])
rules_start = src.index("/*!re2c", end)           # the rules block
# Rule expressions: a line with one leading tab, followed by a line holding only "{".
# The commented-out gnunocolontz rule sits inside a C comment and is skipped.
block = src[rules_start + 1:]
rules = []
in_comment = False
for i, line in enumerate(block):
    if line.strip() == "*/" and not in_comment:
        break
    stripped = line.strip()
    if stripped.startswith("/*") and "*/" not in stripped:
        in_comment = True
    if in_comment:
        if "*/" in stripped:
            in_comment = False
        continue
    if line.startswith("\t") and not line.startswith("\t\t") and stripped and stripped[0] not in "{}/":
        j = i + 1
        while j < len(block) and not block[j].strip():
            j += 1
        if j < len(block) and block[j].strip() == "{":
            rules.append(stripped)
if len(rules) != GROUPS[-1]:
    sys.exit(f"expected {GROUPS[-1]} rules in parse_date.re, found {len(rules)}")

TEMPLATE = """// GENERATED by scripts/date-scanner/gen.py with re2java; do not edit.
// Definitions and rule expressions from timelib 2022.17 parse_date.re,
// Copyright (c) 2015-2021 Derick Rethans, MIT License (see META-INF/LICENSE-timelib).
package dev.phpruntime.timelib;

/** DFA for date rules {lo} to {hi_incl} (indices into ParseDate's rule list). */
final class {name} {{

    private {name}() {{
    }}

    /** Chars above 0xFF cannot occur in byte input; treat them as one non-ASCII byte. */
    private static char peek(String s, int i) {{
        char c = s.charAt(i);
        return c > 0xFF ? (char) 0x80 : c;
    }}

    /**
     * Longest match among this group's rules at {{@code cursor}}: (rule index << 32) | token end,
     * or -1 when none matches. The input must be followed by NUL padding (see ParseDate).
     */
    static long scan(String yyinput, int cursor) {{
        int yycursor = cursor;
        int yymarker = cursor;
        int yyctxmarker = cursor;
        /*!re2c
        re2c:YYCTYPE = "char";
        re2c:YYPEEK = "peek(yyinput, yycursor)";
        re2c:yyfill:enable = 0;
{definitions}
{body}
        * {{ return -1L; }}
        */
    }}
}}
"""

for g in range(len(GROUPS) - 1):
    lo, hi = GROUPS[g], GROUPS[g + 1]
    name = f"DateScanner{g}"
    body = "".join(f"\t{rules[i]}\n\t{{ return ((long) {i} << 32) | yycursor; }}\n" for i in range(lo, hi))
    re_path = os.path.join(HERE, f"{name}.re")
    with open(re_path, "w", encoding="latin-1") as f:
        f.write(TEMPLATE.format(lo=lo, hi_incl=hi - 1, name=name, definitions=definitions, body=body))
    out_path = os.path.join(OUT, f"{name}.java")
    subprocess.run([RE2JAVA, "-Wno-sentinel-in-midrule", re_path, "-o", out_path], check=True)
    os.remove(re_path)
    text = open(out_path, encoding="latin-1").read()
    text = re.sub(r"^// Generated by re2java[^\n]*\n", "", text, flags=re.M)  # drop the timestamp line
    open(out_path, "w", encoding="latin-1").write(text)
    print(f"{name}: rules {lo}..{hi - 1}, {text.count(chr(10))} lines")
