#!/usr/bin/env php
<?php
/**
 * Writes the parameter lists of BlitzVM's builtins to
 * src/main/resources/dev/phpruntime/builtins/params.tsv, for binding named
 * arguments to builtins.
 *
 * The builtin names come from the runtime itself (get_defined_functions() on
 * the BlitzVM launcher), so aliases and the functions registered in loops are
 * included. Names the local php does not have are skipped; parameter names and
 * defaults are php's (ReflectionFunction), because they decide what a named
 * call means.
 *
 * Usage: scripts/builtin-params/gen.php [names-file]
 *
 * The file format, one line per function:
 *
 *   function-name \t name:variadic:default \t name:variadic:default ...
 *
 * `default` is a var_export() literal with backslash, tab, CR and LF escaped,
 * `!` when the parameter is required, or `?` when it is optional but php does
 * not know its default (variadic parameters do not have one either).
 */

declare(strict_types=1);

$root = dirname(__DIR__, 2);

function builtinNames(string $root): array
{
    $bin = $root . '/bin/php-truffle';
    $code = 'echo implode("\n", get_defined_functions()["internal"]);';
    $output = shell_exec(escapeshellarg($bin) . ' -r ' . escapeshellarg($code));
    if ($output === null) {
        fwrite(STDERR, "cannot run $bin\n");
        exit(1);
    }
    return preg_split('/\R/', trim($output));
}

function escapeDefault(string $literal): string
{
    return str_replace(
        ["\\", "\t", "\n", "\r"],
        ["\\\\", "\\t", "\\n", "\\r"],
        $literal,
    );
}

$names = [];
if (isset($argv[1])) {
    $names = preg_split('/\R/', trim(file_get_contents($argv[1])));
} else {
    $names = builtinNames($root);
}

$lines = [];
$skipped = 0;
foreach ($names as $name) {
    $name = trim($name);
    if ($name === '') {
        continue;
    }
    if (!function_exists($name)) {
        $skipped++;
        continue;
    }
    $fields = [$name];
    foreach ((new ReflectionFunction($name))->getParameters() as $param) {
        if ($param->isDefaultValueAvailable()) {
            $default = escapeDefault(var_export($param->getDefaultValue(), true));
        } else {
            // php knows these parameters are optional but not what they default to.
            $default = $param->isOptional() ? '?' : '!';
        }
        $fields[] = $param->getName() . ':' . ($param->isVariadic() ? '1' : '0') . ':' . $default;
    }
    $lines[] = implode("\t", $fields);
}

sort($lines, SORT_STRING);

$header = "# Generated by scripts/builtin-params/gen.php from php " . PHP_VERSION . ".\n"
    . "# function \t name:variadic:default ...; default is a var_export literal\n"
    . "# with \\\\, \\t, \\n and \\r escaped, ! for a required parameter, or ?\n"
    . "# when an optional parameter's default is not known.\n";

$target = $root . '/src/main/resources/dev/phpruntime/builtins/params.tsv';
if (!is_dir(dirname($target)) && !mkdir(dirname($target), 0777, true) && !is_dir(dirname($target))) {
    fwrite(STDERR, "cannot create " . dirname($target) . "\n");
    exit(1);
}
file_put_contents($target, $header . implode("\n", $lines) . "\n");

printf("%d functions, %d missing from php\n", count($lines), $skipped);
