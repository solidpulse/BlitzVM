function describe_value($value): string
{
    if (is_array($value)) {
        return 'array(' . count($value) . ')';
    }
    if ($value === null) {
        return 'null';
    }
    if (is_bool($value)) {
        return $value ? 'true' : 'false';
    }
    if (is_string($value)) {
        return 'string(' . strlen($value) . ')';
    }
    if (is_int($value)) {
        return 'int(' . $value . ')';
    }
    if (is_float($value)) {
        return 'float(' . $value . ')';
    }
    return gettype($value);
}

function check(string $label, callable $call): void
{
    try {
        $result = $call();
        echo $label, ' => OK ', describe_value($result), "\n";
    } catch (TypeError | ValueError $exception) {
        echo $label, ' => ', $exception->getMessage(), "\n";
    }
}

