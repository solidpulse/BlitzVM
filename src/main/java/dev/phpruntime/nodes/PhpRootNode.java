package dev.phpruntime.nodes;

import com.oracle.truffle.api.frame.FrameDescriptor;
import com.oracle.truffle.api.nodes.RootNode;
import com.oracle.truffle.api.source.Source;
import com.oracle.truffle.api.source.SourceSection;
import dev.phpruntime.PhpLanguage;

/** Common base for script and function roots: knows its Source so nodes can report lines. */
public abstract class PhpRootNode extends RootNode {

    private Source source;
    private int line;

    protected PhpRootNode(PhpLanguage language, FrameDescriptor fd, Source source, int line) {
        super(language, fd);
        this.source = source;
        this.line = line;
    }

    /** For generated bytecode roots, whose constructor is fixed: the source is set right after. */
    protected PhpRootNode(PhpLanguage language, FrameDescriptor fd) {
        super(language, fd);
    }

    protected final void initSource(Source s, int l) {
        this.source = s;
        this.line = l;
    }

    public final Source source() {
        return source;
    }

    @Override
    public SourceSection getSourceSection() {
        return PhpNode.section(source, line);
    }
}
