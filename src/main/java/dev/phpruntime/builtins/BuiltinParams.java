package dev.phpruntime.builtins;

import com.oracle.truffle.api.CompilerDirectives.TruffleBoundary;
import dev.phpruntime.runtime.PhpArray;
import dev.phpruntime.runtime.PhpNull;
import dev.phpruntime.runtime.PhpOps;
import dev.phpruntime.runtime.PhpStrings;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.Map;

/**
 * Parameter names and defaults of the builtins, as php declares them, for binding named
 * arguments ({@code str_pad("x", 4, pad_string: "-")}). Generated by
 * {@code scripts/builtin-params/gen.php} into {@code params.tsv}; loaded on the first
 * named builtin call so positional calls and startup do no work.
 */
public final class BuiltinParams {

    /** One declared parameter. {@code defaultValue} is parsed from its {@code var_export} literal. */
    public record Param(String name, boolean variadic, boolean optional, boolean hasDefault, Object defaultValue) {
    }

    private static volatile Map<String, Param[]> table;

    private BuiltinParams() {
    }

    /** The parameters of {@code name}, or null when php has no such function. */
    @TruffleBoundary
    public static Param[] forName(String name) {
        Map<String, Param[]> t = table;
        if (t == null) {
            t = load();
            table = t;
        }
        return t.get(PhpStrings.lower(name));
    }

    @TruffleBoundary
    private static Map<String, Param[]> load() {
        Map<String, Param[]> out = new HashMap<>();
        try (InputStream in = BuiltinParams.class.getResourceAsStream("/dev/phpruntime/builtins/params.tsv")) {
            if (in == null) {
                return out;
            }
            BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            String line;
            while ((line = reader.readLine()) != null) {
                if (line.isEmpty() || line.charAt(0) == '#') {
                    continue;
                }
                String[] fields = line.split("\t", -1);
                Param[] params = new Param[fields.length - 1];
                for (int i = 1; i < fields.length; i++) {
                    String field = fields[i];
                    int first = field.indexOf(':');
                    int second = field.indexOf(':', first + 1);
                    String pName = field.substring(0, first);
                    boolean variadic = field.charAt(first + 1) == '1';
                    String literal = field.substring(second + 1);
                    if (literal.equals("!")) {
                        params[i - 1] = new Param(pName, variadic, false, false, null);
                    } else if (literal.equals("?")) {
                        params[i - 1] = new Param(pName, variadic, true, false, null);
                    } else {
                        params[i - 1] = new Param(pName, variadic, true, true, parseDefault(unescape(literal)));
                    }
                }
                out.put(PhpStrings.lower(fields[0]), params);
            }
        } catch (IOException e) {
            throw new IllegalStateException("cannot read builtin parameter lists", e);
        }
        return out;
    }

    private static String unescape(String escaped) {
        StringBuilder out = new StringBuilder(escaped.length());
        for (int i = 0; i < escaped.length(); i++) {
            char c = escaped.charAt(i);
            if (c != '\\' || i + 1 >= escaped.length()) {
                out.append(c);
                continue;
            }
            char next = escaped.charAt(++i);
            switch (next) {
                case '\\' -> out.append('\\');
                case 't' -> out.append('\t');
                case 'n' -> out.append('\n');
                case 'r' -> out.append('\r');
                default -> out.append('\\').append(next);
            }
        }
        return out.toString();
    }

    /** Parses the {@code var_export} forms php produces for builtin parameter defaults. */
    static Object parseDefault(String text) {
        Parser parser = new Parser(text);
        Object value = parser.value();
        parser.spaces();
        if (!parser.atEnd()) {
            throw new IllegalArgumentException("unsupported default value " + text);
        }
        return value;
    }

    private static final class Parser {
        private final String text;
        private int pos;

        Parser(String text) {
            this.text = text;
        }

        boolean atEnd() {
            return pos >= text.length();
        }

        void spaces() {
            while (pos < text.length() && Character.isWhitespace(text.charAt(pos))) {
                pos++;
            }
        }

        private char peek() {
            return pos < text.length() ? text.charAt(pos) : '\0';
        }

        private boolean accept(String what) {
            spaces();
            if (text.startsWith(what, pos)) {
                pos += what.length();
                return true;
            }
            return false;
        }

        Object value() {
            Object value = primary();
            spaces();
            while (peek() == '.') {
                pos++;
                Object next = primary();
                value = PhpOps.toStr(value).concat(PhpOps.toStr(next));
                spaces();
            }
            return value;
        }

        private Object primary() {
            spaces();
            if (atEnd()) {
                throw new IllegalArgumentException("unexpected end of default value");
            }
            if (text.startsWith("array", pos)) {
                return array();
            }
            if (text.startsWith("NULL", pos)) {
                pos += 4;
                return PhpNull.INSTANCE;
            }
            if (text.startsWith("true", pos)) {
                pos += 4;
                return Boolean.TRUE;
            }
            if (text.startsWith("false", pos)) {
                pos += 5;
                return Boolean.FALSE;
            }
            char c = peek();
            if (c == '\'') {
                return quoted('\'');
            }
            if (c == '"') {
                return quoted('"');
            }
            if (c == '\\') {
                return enumCase();
            }
            if (text.startsWith("-9223372036854775807-1", pos)) {
                pos += "-9223372036854775807-1".length();
                return Long.MIN_VALUE;
            }
            return number();
        }

        private Object array() {
            pos += "array".length();
            spaces();
            if (!accept("(")) {
                throw new IllegalArgumentException("expected ( in array default");
            }
            PhpArray array = new PhpArray();
            while (true) {
                spaces();
                if (accept(")")) {
                    return array;
                }
                Object key = primary();
                if (!accept("=>")) {
                    throw new IllegalArgumentException("expected => in array default");
                }
                Object value = value();
                array.put(key, PhpOps.copyOnAssign(value));
                spaces();
                if (!accept(",")) {
                    throw new IllegalArgumentException("expected , in array default");
                }
            }
        }

        private String quoted(char quote) {
            pos++;
            StringBuilder out = new StringBuilder();
            while (true) {
                if (atEnd()) {
                    throw new IllegalArgumentException("unterminated string in default value");
                }
                char c = text.charAt(pos++);
                if (c == quote) {
                    return out.toString();
                }
                if (c != '\\' || atEnd()) {
                    out.append(c);
                    continue;
                }
                char next = text.charAt(pos++);
                if (quote == '\'') {
                    if (next == '\\' || next == '\'') {
                        out.append(next);
                    } else {
                        out.append('\\').append(next);
                    }
                } else {
                    switch (next) {
                        case '0' -> out.append('\0');
                        case 'n' -> out.append('\n');
                        case 'r' -> out.append('\r');
                        case 't' -> out.append('\t');
                        case '\\', '"', '$' -> out.append(next);
                        default -> out.append('\\').append(next);
                    }
                }
            }
        }

        private Object enumCase() {
            int start = ++pos;
            while (pos < text.length() && !Character.isWhitespace(text.charAt(pos)) && text.charAt(pos) != ','
                    && text.charAt(pos) != ')') {
                pos++;
            }
            String token = text.substring(start, pos);
            int sep = token.indexOf("::");
            if (sep > 0 && token.substring(0, sep).endsWith("RoundingMode")) {
                return switch (token.substring(sep + 2)) {
                    case "HalfAwayFromZero" -> 1L;
                    case "HalfTowardsZero" -> 2L;
                    case "HalfEven" -> 3L;
                    case "HalfOdd" -> 4L;
                    case "TowardsZero" -> 5L;
                    case "AwayFromZero" -> 6L;
                    case "NegativeInfinity" -> 7L;
                    case "PositiveInfinity" -> 8L;
                    default -> PhpNull.INSTANCE;
                };
            }
            return PhpNull.INSTANCE;
        }

        private Object number() {
            int start = pos;
            if (peek() == '-' || peek() == '+') {
                pos++;
            }
            boolean floating = false;
            while (pos < text.length()) {
                char c = text.charAt(pos);
                if (c >= '0' && c <= '9') {
                    pos++;
                } else if (c == '.' || c == 'e' || c == 'E') {
                    floating = true;
                    pos++;
                } else if ((c == '-' || c == '+') && pos > start
                        && (text.charAt(pos - 1) == 'e' || text.charAt(pos - 1) == 'E')) {
                    pos++;
                } else {
                    break;
                }
            }
            String token = text.substring(start, pos);
            return floating ? (Object) Double.parseDouble(token) : (Object) Long.parseLong(token);
        }
    }
}
